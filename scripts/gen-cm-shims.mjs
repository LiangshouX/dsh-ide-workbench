/**
 * Generate the CodeMirror shims of the codeintel plugin.
 *
 * The codeintel must NOT bundle its own copy of `@codemirror/state` and
 * friends: the extensions of CodeMirror are checked with `instanceof`, and
 * two copies of a library break that check (the error text of CodeMirror
 * itself says so: "multiple instances of @codemirror/state are loaded").
 *
 * The core owns the one CodeMirror runtime of the process and publishes it
 * on `globalThis[Symbol.for('dsh.ide-workbench.codemirror')]`. The shims of
 * this plugin resolve the runtime **at the moment of the access**, so a
 * plugin that is installed alone does not fail while it is being loaded: the
 * error appears only when a capability is really used, and it can be caught.
 *
 * A CJS module with `module.exports = new Proxy(...)` would NOT work: esbuild
 * copies the properties of a CommonJS module with LAZY getters, but it asks
 * the proxy for its own keys - and a proxy without an `ownKeys` trap reports
 * none, so the named imports would be `undefined`. The shims are therefore
 * ES modules with one lazy proxy per exported name.
 *
 * The list of the names is taken from the packages themselves, so a shim
 * never lags behind the library it stands in for. Run this script after a
 * CodeMirror upgrade:
 *
 *     node scripts/gen-cm-shims.mjs
 */
import { readFileSync } from 'node:fs'
import { writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = resolve(root, 'packages', 'codeintel', 'src', 'client', 'vendor')
const PACKAGES = ['state', 'view', 'language', 'autocomplete', 'lint', 'commands', 'search']

/**
 * The exported names of one package.
 * @param {string} name the name of the package
 * @returns {string[]} the names
 */
function exportedNames(name) {
  const file = resolve(root, 'node_modules', '@codemirror', name, 'dist', 'index.js')
  const text = readFileSync(file, 'utf8')
  const names = new Set()
  for (const block of text.match(/export\s*\{([\s\S]*?)\}/g) ?? []) {
    const inner = block.replace(/^export\s*\{/, '').replace(/\}\s*$/, '')
    for (const part of inner.split(',')) {
      const trimmed = part.trim()
      if (trimmed === '') continue
      const alias = trimmed.split(/\s+as\s+/)
      const exported = (alias[1] ?? alias[0]).trim()
      if (exported === '' || exported.startsWith('__')) continue
      names.add(exported)
    }
  }
  return [...names].sort()
}

await mkdir(target, { recursive: true })

for (const name of PACKAGES) {
  const names = exportedNames(name)
  const lines = [
    '/**',
    ' * The shim of `@codemirror/' + name + '`.',
    ' *',
    ' * GENERATED by `scripts/gen-cm-shims.mjs` - do not edit by hand.',
    ' *',
    ' * Every export is a lazy proxy: the runtime of the core is resolved when',
    ' * the property is read, not when this module is loaded. A codeintel that',
    ' * is installed alone therefore loads without an error, and only the real',
    ' * use of the editor fails - with a message that names the missing plugin.',
    ' */',
    "import { lazyProxy } from './cm-runtime.js'",
    '',
  ]
  for (const exported of names) {
    lines.push(`export const ${exported} = lazyProxy('${name}', '${exported}')`)
  }
  lines.push('')
  await writeFile(resolve(target, `cm-${name}.js`), lines.join('\n'), 'utf8')
  console.log(`cm-${name}.js: ${names.length} names`)
}
